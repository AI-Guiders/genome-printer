@dataclass(frozen=True)
class MSubshellChannel:
    """Dimensionless cuboctahedral channel specification (channel_id 0..3 -> l = 0..3)."""

    channel_id: int  # 0: core (s), 1: squares (p), 2: vertices (d), 3: triangles+edges (f)
    l_quantum: int
    opens_at_shell_k: int
    spatial_modes: int
    spin_capacity: int


def m_cuboctahedral_subshells(c: MCarrierConstants = M_CARRIER) -> tuple[MSubshellChannel, ...]:
    """Return the 4 subshells generated by the 4 geometric families of FCC N12."""
    return (
        MSubshellChannel(0, 0, 0, 1, 2),
        MSubshellChannel(1, 1, 1, c.d, 2 * c.d),
        MSubshellChannel(2, 2, 2, c.d_out_e, 2 * c.d_out_e),
        MSubshellChannel(3, 3, 2, c.d_out_v, 2 * c.d_out_v),
    )


def m_ionization_ratio_be_h(z: int, c: MCarrierConstants = M_CARRIER) -> float:
    """Dimensionless first ionization energy IE_1(Z) / BE_H for Z = 1..10."""
    seam = 1.0 / (c.n_12 * c.n_phi)  # 1 / 156
    if z == 1:
        return 1.0
    if z == 2:
        f_open = 1.0 - (1.0 / c.n_12) - seam  # 71 / 78
        return 2.0 * f_open

    z_li_base = c.d - 2.0 * (1.0 - 1.0 / c.n_hier)  # 5 / 4
    delta_z_sq = (1.0 / c.d_in_sq) + seam  # 10 / 39
    z_sq_start = c.d_in_sq + 1  # 5 (opening of the 2p square_6 channel)

    if z == c.d:
        z_eff = z_li_base + seam
    elif z == c.d_in_sq:
        z_eff = z_li_base + (1.0 - c.d_out_v / c.n_12) - seam
    elif z_sq_start <= z <= c.d_out_v:
        z_eff = (z_li_base ** 2) + (z - z_sq_start) * delta_z_sq
    elif c.n_hier <= z <= c.n_hier + (c.d - 1):
        z_eff = (c.n_hier - c.n_squares) + (z - c.n_hier) * delta_z_sq
    else:
        return 0.0

    return (z_eff / (c.d - 1.0)) ** 2


def m_covalent_radius_in_a0(z: int, bond_order: int = 1, c: MCarrierConstants = M_CARRIER) -> float:
    """Dimensionless covalent radius r_cov(Z) / a_0 for Z=1, Z=4..9, and Z=14..16."""
    if z == 1:
        r_single = c.kappa
    elif c.d_in_sq <= z <= c.mod_bits:
        r_single = ((c.d * c.n_phi - 2 * z) / c.n_phi) * c.kappa
    elif (c.n_12 + 2) <= z <= (c.n_12 + c.d_in_sq):
        r_p2 = m_covalent_radius_in_a0(z - c.n_hier, bond_order=1, c=c)
        r_single = r_p2 + (c.n_12 / c.n_phi) * c.kappa
    else:
        return 0.0

    return r_single * (c.kappa_hex ** (bond_order - 1))


def m_find_hydrogen_commensurate_backbone_pairs(
    c: MCarrierConstants = M_CARRIER,
) -> tuple[tuple[int, int], ...]:
    """Find all p-block square-channel pairs (Z1 < Z2 in 5..8) whose single-bond length is an exact integer multiple of r_cov(1).

    Because r_cov(Z) / r_cov(1) = (39 - 2*Z) / 13, exact commensurability with the hydrogen
    cuboctahedron requires (39 - 2*Z1) + (39 - 2*Z2) == 4 * 13 <=> Z1 + Z2 == N_phi == 13,
    yielding exactly two solutions in channel square_6:
      - (5, 8) [B-O: prebiotic ribose-stabilizing borate lock & anhydrous high-T polymer twin],
      - (6, 7) [C-N: aqueous peptide & nucleic-acid backbone in the [T_melt, T_boil] H2O window].
    """
    r_h = m_covalent_radius_in_a0(1, bond_order=1, c=c)
    z_sq_start = c.d_in_sq + 1
    z_sq_end = c.n_hier
    pairs: list[tuple[int, int]] = []
    for z1 in range(z_sq_start, z_sq_end + 1):
        for z2 in range(z1 + 1, z_sq_end + 1):
            ratio = (m_covalent_radius_in_a0(z1, bond_order=1, c=c) + m_covalent_radius_in_a0(z2, bond_order=1, c=c)) / r_h
            if abs(ratio - round(ratio)) < 1e-12:
                pairs.append((z1, z2))
    return tuple(pairs)


def m_ionization_energy_e0(z: int, c: MCarrierConstants = M_CARRIER) -> float:
    """First ionization energy IE_1(Z) in native cell energy units E_0 = s_0 / dt."""
    return m_ionization_ratio_be_h(z, c=c) * c.be_h_e0


def m_covalent_radius_dh(z: int, bond_order: int = 1, c: MCarrierConstants = M_CARRIER) -> float:
    """Covalent radius r_cov(Z) in native cell length steps dh = 1 (via N_a0 = round(N_c / alpha_fs))."""
    return m_covalent_radius_in_a0(z, bond_order=bond_order, c=c) * c.a_0_dh


def m_sp3_bond_angle_cos(lone_pairs: int = 0, c: MCarrierConstants = M_CARRIER) -> float:
    """Exact cosine of the sp3 tetrahedral bond angle on K_4 with `lone_pairs` in {0, 1, 2}:

    cos(theta) = -1/d + m_LP * delta_pack = -(8 - m_LP) / 24.
    """
    return -1.0 / c.d + lone_pairs * c.delta_pack


def m_sp3_bond_angle_rad(lone_pairs: int = 0, c: MCarrierConstants = M_CARRIER) -> float:
    """Bond angle in radians on K_4 with `lone_pairs` in {0, 1, 2}."""
    return math.acos(m_sp3_bond_angle_cos(lone_pairs, c=c))


@dataclass(frozen=True)
class MHBondPhaseRatios:
    """Dimensionless phase-transition ratios of the tetrahedral H2O network in units of E_HB and T_HB."""

    n_hb_divisor: int  # 63
    vap_in_ehb_quanta: float  # d - 1 = 2.0
    fus_in_ehb_quanta: float  # (d - 1) / d_soft = 2 / 7
    t_melt_over_t_hb: float  # 1 / floor(B_V) = 1 / 9
    t_boil_over_t_hb: float  # d_in(sq) / d^3 = 4 / 27
    t_crit_over_t_hb: float  # N_hier / (d_in(sq)*N_hier - 1) = 8 / 31
    bcs_gap_ratio: float  # (d_soft / 2) * M_hat / (M_hat - 1) = (7/2)*(97/96)


def m_compute_hbond_phase_ratios(c: MCarrierConstants = M_CARRIER) -> MHBondPhaseRatios:
    """Compute dimensionless tetrahedral H-bond phase transition ratios on FCC N12."""
    return MHBondPhaseRatios(
        n_hb_divisor=c.n_hb,
        vap_in_ehb_quanta=float(c.d - 1),
        fus_in_ehb_quanta=(c.d - 1.0) / c.d_out_v,
        t_melt_over_t_hb=1.0 / c.mod_bits,
        t_boil_over_t_hb=c.d_in_sq / float(c.d ** 3),
        t_crit_over_t_hb=c.n_hier / float(c.d_in_sq * c.n_hier - 1),
        bcs_gap_ratio=(c.d_out_v / 2.0) * (c.m_hat / (c.m_hat - 1.0)),
    )


@dataclass(frozen=True)
class MThermalMobilityWindow:
    """Dimensionless carrier mobility window [1/floor(B_V), d_in(sq)/d^3] * E_soft^(m), E_hard >= |N_12| * E_soft^(m), and 5:6:7 geometry."""

    rung_m: int  # -1 (cryogenic fus_quantum = 2/7), 0 (unit E_HB = 1), +1 (vap_quantum = 2)
    e_soft_in_ehb_quanta: float
    min_e_hard_in_ehb_quanta: float  # |N_12| * e_soft_in_ehb_quanta
    t_min_over_t_hb: float  # (1 / floor(B_V)) * e_soft_in_ehb_quanta
    t_max_over_t_hb: float  # (d_in(sq) / d^3) * e_soft_in_ehb_quanta
    reduced_wavelength_in_a0: float  # ((d - 1) * N_HB) / (alpha_fs * e_soft_in_ehb_quanta) in {441, 126, 63} / alpha_fs (zero pi!)
    reduced_wavelength_dh: float  # reduced_wavelength_in_a0 * N_a0 * dh
    scale_invariant_5_6_7: int  # |square| + m in {d_out(E)=5, |square|=6, d_out(V)=7}
    backbone_bond_in_kappa_a0: float  # (d_in(sq) + m*(d-1)/d) in {10/3, 12/3=4, 14/3}
    helix_pitch_in_kappa_a0: float  # ((|N_12| + |square|) / d_out(E)) * backbone_bond_in_kappa_a0
    membrane_tm18_in_kappa_a0: float  # scale_invariant_5_6_7 * |N_12| in {60, 72, 84}
    duplex_stack_in_kappa_a0: float  # (mod_bits / d_in(sq)) * backbone_bond_in_kappa_a0


def m_compute_life_thermal_windows(
    c: MCarrierConstants = M_CARRIER,
) -> tuple[MThermalMobilityWindow, ...]:
    """Compute the 3 dimensionless thermal mobility windows inherited from `MHBondPhaseRatios` (2/7, 1, 2 E_HB) and their 5:6:7 geometry."""
    d_pol = c.d - c.d_in_v
    ratios = m_compute_hbond_phase_ratios(c=c)
    quanta_ladder = (
        (-c.d_in_v, ratios.fus_in_ehb_quanta),
        (0, float(c.d_in_v)),
        (c.d_in_v, ratios.vap_in_ehb_quanta),
    )
    n_tm_units = c.n_12 + c.n_squares  # 18
    n_alpha_turn = float(n_tm_units) / float(c.d_out_e)  # 18 / 5 = 3.6
    stack_over_bond = float(c.mod_bits) / float(c.d_in_sq)  # 9 / 4
    out: list[MThermalMobilityWindow] = []
    for rung, q in quanta_ladder:
        wl_bar_a0 = (ratios.n_hb_divisor / q) * c.reduced_lyman_wavelength_in_a0
        scale_k = c.n_squares + rung  # {5, 6, 7}
        r_bond_ka0 = float(c.d_in_sq) + float(rung * d_pol) / float(c.d)  # {10/3, 4, 14/3}
        out.append(
            MThermalMobilityWindow(
                rung_m=rung,
                e_soft_in_ehb_quanta=q,
                min_e_hard_in_ehb_quanta=float(c.n_12) * q,
                t_min_over_t_hb=ratios.t_melt_over_t_hb * q,
                t_max_over_t_hb=ratios.t_boil_over_t_hb * q,
                reduced_wavelength_in_a0=wl_bar_a0,
                reduced_wavelength_dh=wl_bar_a0 * c.a_0_dh,
                scale_invariant_5_6_7=scale_k,
                backbone_bond_in_kappa_a0=r_bond_ka0,
                helix_pitch_in_kappa_a0=n_alpha_turn * r_bond_ka0,
                membrane_tm18_in_kappa_a0=float(n_tm_units) * r_bond_ka0,
                duplex_stack_in_kappa_a0=stack_over_bond * r_bond_ka0,
            )
        )
    return tuple(out)


@dataclass(frozen=True)
class MElectronClusterStructure:
    """Dimensionless M-layer internal structure of the B=0, |Q|=1 electron cluster and its d=3 axis generations."""

    baryon_number: int  # 0 (no K_3 triangular clique)
    cluster_nodes: int  # N_phi = 1 + |N_12| = 13
    axial_partition: tuple[int, int, int, int]  # (1_core, d_in(V)=1, d_lat(V)=4, d_out(V)=7)
    generations_count: int  # d = 3 orthogonal axes
    koide_invariant: float  # (d - 1) / d = 2 / 3
    generation_mass_ratios: tuple[float, float, float]  # (1, m_mu/m_e, m_tau/m_e)
    open_mu_decay_channels: int  # |N_12| * (N_ring - N_phi) = 5988


def m_compute_electron_cluster_structure(
    c: MCarrierConstants = M_CARRIER,
) -> MElectronClusterStructure:
    """Derive the 13-node internal partition and d=3 generation mass ratios of the B=0 electron rotor."""
    d_pol = c.d - c.d_in_v
    axial = (c.d_in_v, c.d_in_v, c.d_lat_v, c.d_out_v)
    delta_0 = float(d_pol) / float(c.mod_bits)
    # 3 orthogonal axis projections of the 13-node rotor on FCC N_12
    full_turn = 2.0 * math.acos(-1.0)
    weights = sorted(
        (1.0 + (1.0 / c.kappa) * math.cos(full_turn * float(g) / float(c.d) + delta_0)) ** d_pol
        for g in range(c.d)
    )
    ratios = (
        1.0,
        weights[1] / weights[0],
        weights[2] / weights[0],
    )
    koide_q = sum(weights) / (sum(math.sqrt(w) for w in weights) ** d_pol)
    open_mu = c.n_12 * (c.n_ring - c.n_phi)
    return MElectronClusterStructure(
        baryon_number=0,
        cluster_nodes=sum(axial),
        axial_partition=axial,
        generations_count=c.d,
        koide_invariant=koide_q,
        generation_mass_ratios=ratios,
        open_mu_decay_channels=open_mu,
    )


@dataclass(frozen=True)
class MPeriodicSystemStructure:
    """Dimensionless M-layer periodic table and nuclear magic shell closure invariants."""

    subshell_capacities: tuple[int, ...]  # (2, 6, 10, 14)
    period_lengths: tuple[int, ...]  # (2, 8, 8, 18, 18, 32, 32)
    noble_gas_closures: tuple[int, ...]  # (2, 10, 18, 36, 54, 86, 118)
    nuclear_magic_low: tuple[int, ...]  # (2, 8, 20)
    nuclear_magic_high: tuple[int, ...]  # (28, 50, 82, 126)
    nuclear_magic_all: tuple[int, ...]  # (2, 8, 20, 28, 50, 82, 126)
    terminal_stable_z: int  # 2 * Delta_phi_disc = 82 (Pb)
    terminal_stable_n: int  # 2 * N_HB = 126
    terminal_stable_a: int  # 2 * N_hier * N_phi = 208 (Pb-208)
    island_of_stability_n: int  # M_high(N_hier = 8) = 184
    island_of_stability_z_bounds: tuple[int, int]  # (126 - |N_12| = 114, 126 - |square| = 120)
    fission_ceiling_z: int  # 2 * N_HB = 126 (unperturbed proton closure / spontaneous fission limit)
    electromagnetic_ceiling_z: int  # d_in(sq)^2 + (|N_12| - 1)^2 = 137 (point-nucleus Dirac limit)
    period_8_remaining_count: int  # 137 - 118 = 19 = N_phi + |square|
    period_8_channel_partition: tuple[int, int, int]  # (2, 14, 3) = (C_0(V), C_3(triangle), d(square))
    finite_nucleus_qed_diving_z_bounds: tuple[int, int]  # (137 + d_out(E)*d_out(V) = 172, 137 + |square|^2 = 173)


def m_compute_periodic_and_nuclear_shells(
    c: MCarrierConstants = M_CARRIER,
) -> MPeriodicSystemStructure:
    """Derive electronic periods, nuclear magic shells, Pb-208 terminal closure, N=184 island, and Z_max limits."""
    d_pol = c.d - c.d_in_v
    subshells = m_cuboctahedral_subshells(c=c)
    caps = tuple(ch.spin_capacity for ch in subshells)

    n_periods = c.d_out_v  # 7 periods up to Z = 118
    p_lengths = tuple(
        d_pol * (((p + d_pol) // d_pol) ** d_pol)
        for p in range(c.d_in_v, n_periods + c.d_in_v)
    )
    nobles = tuple(sum(p_lengths[:i]) for i in range(c.d_in_v, n_periods + c.d_in_v))

    low_k = (c.d_in_v, c.d_in_e, c.d_in_tri)
    magic_low = tuple((k * (k + c.d_in_v) * (k + d_pol)) // c.d for k in low_k)

    high_k = (c.d_in_sq, c.d_out_e, c.n_squares, c.d_out_v)
    magic_high = tuple((k * ((k ** d_pol) + c.d_out_e)) // c.d for k in high_k)

    z_term = d_pol * c.delta_phi_disc
    n_term = d_pol * c.n_hb
    a_term = d_pol * c.n_hier * c.n_phi

    k_island = c.n_hier
    n_island = (k_island * ((k_island ** d_pol) + c.d_out_e)) // c.d
    z_island_bounds = (n_term - c.n_12, n_term - c.n_squares)
    z_fission = n_term
    z_em_ceiling = (c.d_in_sq ** d_pol) + ((c.n_12 - c.d_in_v) ** d_pol)
    p8_partition = (caps[0], caps[-1], c.d)
    p8_remaining = z_em_ceiling - nobles[-1]
    z_qed_diving = (
        z_em_ceiling + c.d_out_e * c.d_out_v,
        z_em_ceiling + (c.n_squares ** d_pol),
    )

    return MPeriodicSystemStructure(
        subshell_capacities=caps,
        period_lengths=p_lengths,
        noble_gas_closures=nobles,
        nuclear_magic_low=magic_low,
        nuclear_magic_high=magic_high,
        nuclear_magic_all=magic_low + magic_high,
        terminal_stable_z=z_term,
        terminal_stable_n=n_term,
        terminal_stable_a=a_term,
        island_of_stability_n=n_island,
        island_of_stability_z_bounds=z_island_bounds,
        fission_ceiling_z=z_fission,
        electromagnetic_ceiling_z=z_em_ceiling,
        period_8_remaining_count=p8_remaining,
        period_8_channel_partition=p8_partition,
        finite_nucleus_qed_diving_z_bounds=z_qed_diving,
    )


@dataclass(frozen=True)
class MFccGraphDiracSpectrum:
    """Discrete M-layer Dirac spectrum on coordination spheres S_k of FCC N12 (zero continuum, zero pi)."""

    green_core_k0: float  # G_FCC(0) = d + G_FCC(1) ~ 3.9158425 (finite!)
    green_shell_k1: float  # G_FCC(1) = sum_{m>=2} d / (m^d - (m-1)^d) ~ 0.9158425
    core_step_jump: int  # G_FCC(0) - G_FCC(1) = d = 3
    z_core_zero_crossing: int  # Z where k=0 core mode crosses E = 0 (Z = 81, at Pb-208 boundary Z = 82 E < 0)
    e_core_at_lead_82: float  # E_core(Z = 82) < 0
    z_core_continuum_diving: int  # Z where k=0 core mode dives below E = -1 (Z = 123, after Z = 122)
    e_core_before_diving_122: float  # E_core(Z = 122) ~ -0.9923 > -1
    e_1s_shell_at_137: float  # E_1s(Z = 137) ~ +0.6331 > 0 (nonsingular!)
    e_1s_hard_core_at_137: float  # E_1s(Z = 137, k >= 1) ~ +0.6529 > 0
    z_1s_hard_core_zero_crossing: int  # Z where hard-core k >= 1 1s shell mode crosses E = 0 (Z = 270)


def m_fcc_harmonic_green_function(
    k_max: int,
    c: MCarrierConstants = M_CARRIER,
) -> tuple[float, ...]:
    """Compute exact discrete harmonic potential G_FCC(k) on coordination spheres S_k from discrete Gauss law."""
    tail_m = c.n_ring * c.d_in_sq  # 2048 shells
    # Backward cumulative sum of d / (m^d - (m - 1)^d)
    acc = 0.0
    vals = [0.0] * (tail_m + 1)
    for m in range(tail_m, 0, -1):
        step_edges_over_n12 = (m ** c.d) - ((m - c.d_in_v) ** c.d)
        acc += float(c.d) / float(step_edges_over_n12)
        vals[m - 1] = acc
    return tuple(vals[: k_max + 1])


def m_solve_fcc_graph_dirac_spectrum(
    c: MCarrierConstants = M_CARRIER,
) -> MFccGraphDiracSpectrum:
    """Solve the discrete M-layer Dirac operator on FCC N12 coordination spheres S_k via Sturm recurrence."""
    d_pol = c.d - c.d_in_v
    k_max = c.m_hat + c.d  # 100 coordination spheres
    n_sh = tuple(fcc_shell_count(k) for k in range(k_max + 1))
    g_fcc = m_fcc_harmonic_green_function(k_max=k_max, c=c)

    geom_norm = float(c.n_12 - d_pol) / float(c.d)
    a_hop = [0.0] * (k_max + 1)
    b_hop = [0.0] * (k_max + 1)
    for k in range(c.d_in_v, k_max + 1):
        ew = float(fcc_inter_shell_edge_count(k)) / float(c.n_12)
        a_hop[k] = math.sqrt(geom_norm * ew / float(n_sh[k - 1]))
        b_hop[k] = math.sqrt(geom_norm * ew / float(n_sh[k]))

    alpha = c.alpha_fs

    def count_below(z: int, energy: float, start_k: int) -> int:
        neg_pivots = 0
        prev_pivot = 0.0
        for k in range(start_k, k_max + 1):
            v_node = -float(z) * alpha * g_fcc[k]
            diag = 1.0 + v_node - energy
            if k >= c.d_in_v:
                v_edge_in = -float(z) * alpha * (
                    0.5 * (g_fcc[k - 1] + g_fcc[k]) if start_k == 0 else g_fcc[k]
                )
                denom_in = 1.0 + energy - v_edge_in
                diag += (b_hop[k] ** d_pol) / denom_in
                if k > start_k:
                    off_sq = ((a_hop[k] * b_hop[k]) / denom_in) ** d_pol
                    pivot = diag - off_sq / prev_pivot
                else:
                    pivot = diag
            else:
                pivot = diag
            if k < k_max:
                v_edge_out = -float(z) * alpha * (
                    0.5 * (g_fcc[k] + g_fcc[k + 1]) if start_k == 0 else g_fcc[k + 1]
                )
                denom_out = 1.0 + energy - v_edge_out
                pivot += (a_hop[k + 1] ** d_pol) / denom_out
            if pivot < 0.0:
                neg_pivots += 1
            prev_pivot = pivot if abs(pivot) > 1e-30 else 1e-30
        return neg_pivots

    def bisect_eval(z: int, target_idx: int, start_k: int) -> float:
        lo, hi = -0.9999999, 0.9999999
        if count_below(z, lo, start_k) > target_idx:
            return -1.0
        n_iter = c.n_shell_2 + c.n_12  # 54 binary-search steps
        for _ in range(n_iter):
            mid = 0.5 * (lo + hi)
            if count_below(z, mid, start_k) > target_idx:
                hi = mid
            else:
                lo = mid
        return 0.5 * (lo + hi)

    z_lead = d_pol * c.delta_phi_disc  # 82
    z_feynman = (c.d_in_sq ** d_pol) + ((c.n_12 - c.d_in_v) ** d_pol)  # 137

    # Find first Z where k=0 core mode crosses E = 0
    z_core_zero = z_lead
    for z_cand in range(z_lead - c.n_hier, z_lead + c.n_hier):
        if count_below(z_cand, 0.0, 0) >= c.d_in_v:
            z_core_zero = z_cand
            break

    # Find first Z where k=0 core mode dives below E = -1
