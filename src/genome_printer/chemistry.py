"""Atomic shells Z=1..16, covalent radii, bond angles, and water thermodynamics on FCC N12.

Implements the exact parameter-free formulas of Volume 5 (`chemistry`) of "Кипящий океан":
  - Four channels of the cuboctahedron (V, E, square, triangle) -> spdf subshells (2, 6, 10, 14),
  - Ionization energies IE_1(Z) for Z = 1..10 without Slater fitting,
  - Covalent radii r_cov(Z) for Period 2 (Z = 6..9) and Period 3 (Z = 14..16),
  -Multiple bond contraction via hexagonal slice projection kappa_hex = sqrt(3)/2,
  - Tetrahedral sp3 angle cos(theta) = -1/d = -1/3 and lone-pair vertex compression
    Delta_cos = (1 - kappa^2) / |N_12| = 1/24 = delta_pack (NH3 = 107.09 deg, H2O = 104.48 deg),
  - Water phase transitions (Delta_H_vap, Delta_H_fus, T_melt, T_boil, T_crit) and BCS gap ratio.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from .constants import CARRIER, CarrierConstants


@dataclass(frozen=True)
class SubshellChannel:
    """Mapping between a cuboctahedral geometric family and an atomic (s, p, d, f) subshell."""

    symbol: str
    l_quantum: int
    opens_at_shell_k: int
    carrier_family: str
    spatial_modes: int
    spin_capacity: int


def cuboctahedral_subshells(c: CarrierConstants = CARRIER) -> tuple[SubshellChannel, ...]:
    """Return the 4 subshells (s, p, d, f) generated by the 4 geometric families of FCC N12."""
    return (
        SubshellChannel("s", 0, 0, "Core (k=0)", 1, 2),
        SubshellChannel("p", 1, 1, "Squares |square|=6 (3 axes)", c.d, 2 * c.d),
        SubshellChannel("d", 2, 2, "Vertices |V|=12 (5 quadrupoles)", c.d_out_e, 2 * c.d_out_e),
        SubshellChannel("f", 3, 2, "Triangles |triangle|=8 + Edges |E|=24 (7 octupoles)", c.d_out_v, 2 * c.d_out_v),
    )


def first_ionization_energy_ev(z: int, c: CarrierConstants = CARRIER) -> float:
    """Parameter-free first ionization energy IE_1(Z) in eV for Z = 1..10 (Table 2.1 of Vol. 5)."""
    be = c.be_h_ev
    seam = 1.0 / (c.n_12 * c.n_phi)  # 1 / 156 cluster seam
    if z == 1:
        # H (1s^1)
        return be
    if z == 2:
        # He (1s^2): Z * (1 - 1/|N_12| - 1/(|N_12|*N_phi)) * BE_H = (71/39) * BE_H
        f_open = 1.0 - (1.0 / c.n_12) - seam
        return 2.0 * f_open * be

    # Period 2 (n = 2): IE_1(Z) = (Z_eff(Z) / 2)^2 * BE_H
    z_li_base = 3.0 - 2.0 * (1.0 - 1.0 / c.n_hier)  # 3 - 2*(7/8) = 5/4
    delta_z_sq = (1.0 / c.d_in_sq) + seam  # 1/4 + 1/156 = 10/39

    if z == 3:
        # Li (2s^1): Z_eff = 5/4 + 1/156 = 196/156
        z_eff = z_li_base + seam
    elif z == 4:
        # Be (2s^2): Z_eff = 5/4 + (1 - d_out(V)/|N_12|) - 1/156 = 5/3 - 1/156
        z_eff = z_li_base + (1.0 - c.d_out_v / c.n_12) - seam
    elif 5 <= z <= 7:
        # B, C, N (2p^1..3): Z_eff(Z) = (5/4)^2 + (Z - 5) * Delta_Z_sq
        z_eff = (z_li_base ** 2) + (z - 5) * delta_z_sq
    elif 8 <= z <= 10:
        # O, F, Ne (2p^4..6 with Pauli pairing screening sigma(O) = |square| = 6):
        # Z_eff(Z) = (8 - |square|) + (Z - 8) * Delta_Z_sq = 2 + (Z - 8) * (10/39)
        z_eff = (8.0 - c.n_squares) + (z - 8) * delta_z_sq
    else:
        raise ValueError(f"Ionization energy formula in Period 1-2 expects Z in 1..10, got Z={z}.")

    return ((z_eff / 2.0) ** 2) * be


def covalent_radius_angstrom(z: int, bond_order: int = 1, c: CarrierConstants = CARRIER) -> float:
    """Covalent radius r_cov(Z) in Angstroms for Z=1, Z=6..9 (Period 2), and Z=14..16 (Period 3).

    For multiple bonds (bond_order = 2 for sp2 double, bond_order = 3 for sp triple),
    applies the hexagonal slice contraction factor kappa_hex^(bond_order - 1) = (sqrt(3)/2)^(m - 1).
    """
    if bond_order not in (1, 2, 3):
        raise ValueError(f"bond_order must be 1, 2, or 3; got {bond_order}.")

    scale = c.kappa * c.a_0_angstrom
    if z == 1:
        # H: R_e(H2)/2 = a_0 / sqrt(2) = kappa * a_0
        r_single = scale
    elif 6 <= z <= 9:
        # Period 2 (C, N, O, F): r_cov(Z) = [(3 * N_phi - 2 * Z) / N_phi] * kappa * a_0 = [(39 - 2Z)/13] * kappa * a_0
        r_single = ((c.d * c.n_phi - 2 * z) / c.n_phi) * scale
    elif 14 <= z <= 16:
        # Period 3 (Si, P, S): r_cov(Z_3) = r_cov(Z_3 - 8) + (8/9) * kappa * a_0
        r_p2 = covalent_radius_angstrom(z - c.n_hier, bond_order=1, c=c)
        r_single = r_p2 + (c.n_hier / c.mod_bits) * scale
    else:
        raise ValueError(f"Unsupported atomic number Z={z}; expected 1, 6..9, or 14..16.")

    return r_single * (c.kappa_hex ** (bond_order - 1))


def sp3_bond_angle_deg(lone_pairs: int = 0, c: CarrierConstants = CARRIER) -> float:
    """Bond angle of an sp3 center on K_4 with `lone_pairs` non-bonding pairs (0: CH4, 1: NH3, 2: H2O).

    cos(theta_L) = -1/d + L * (1 - kappa^2)/|N_12| = -1/3 + L / 24.
    """
    if lone_pairs not in (0, 1, 2):
        raise ValueError(f"lone_pairs must be 0, 1, or 2; got {lone_pairs}.")
    cos_theta = -1.0 / c.d + lone_pairs * c.delta_pack
    return math.degrees(math.acos(cos_theta))


@dataclass(frozen=True)
class WaterThermodynamics:
    """Parameter-free water phase-transition heats/temperatures and BCS gap ratio."""

    e_hb_ev: float
    e_hb_kj_mol: float
    t_hb_kelvin: float
    delta_h_vap_kj_mol: float
    delta_h_fus_kj_mol: float
    t_melt_kelvin: float
    t_boil_kelvin: float
    t_crit_kelvin: float
    bcs_gap_ratio: float


def compute_water_thermodynamics(c: CarrierConstants = CARRIER) -> WaterThermodynamics:
    """Compute H2O phase transitions and Cooper-BCS gap ratio from E_HB and d_soft = 7."""
    k_b_ev_per_k = 8.617333262e-5
    t_hb = c.e_hb_ev / k_b_ev_per_k  # ~2506.15 K
    delta_h_vap = (c.d - 1) * c.e_hb_kj_mol  # 2 * E_HB
    delta_h_fus = ((c.d - 1) / c.d_out_v) * c.e_hb_kj_mol  # (2/7) * E_HB
    t_melt = t_hb / c.mod_bits  # T_HB / 9
    t_boil = (c.d_in_sq / (c.d ** 3)) * t_hb  # (4/27) * T_HB
    t_crit = (c.n_hier / (c.d_in_sq * c.n_hier - 1)) * t_hb  # (8/31) * T_HB
    bcs_gap = (c.d_out_v / 2.0) * (c.m_hat / (c.m_hat - 1.0))  # (7/2) * (97/96)
    return WaterThermodynamics(
        e_hb_ev=c.e_hb_ev,
        e_hb_kj_mol=c.e_hb_kj_mol,
        t_hb_kelvin=t_hb,
        delta_h_vap_kj_mol=delta_h_vap,
        delta_h_fus_kj_mol=delta_h_fus,
        t_melt_kelvin=t_melt,
        t_boil_kelvin=t_boil,
        t_crit_kelvin=t_crit,
        bcs_gap_ratio=bcs_gap,
    )
